# Folders whose source files are CSV (comma-delimited with headers) rather than
# the usual pipe-delimited convention. Default separator is '|' for everything
# in PIPE_DELIMITED_WITH_HEADERS.
COMMA_DELIMITED_FOLDERS: dict[str, set[str]] = {
    'FHLMC': {'FRE_Multilender'},
}


def _separator_for(gse: str, folder: str) -> str:
    """Return the field separator for a given (GSE, folder) pair."""
    if folder in COMMA_DELIMITED_FOLDERS.get(gse, set()):
        return ','
    return '|'


