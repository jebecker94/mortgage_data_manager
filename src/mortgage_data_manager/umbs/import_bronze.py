def process_zip_to_per_rt_parquet(
    zip_path: Path,
    output_dir: Path,
    *,
    overwrite: bool = False,
) -> dict[str, int]:
    """Split a headerless multi-record-type zip into per-record-type parquets.

    Files like FNM_ISS, FRE_ISS, FNM_MS, etc. are pipe-delimited with no
    header row. Field 0 of each line is a Record Type code (e.g. "1", "2",
    "16"); the remaining field count depends on the record type. This
    function partitions the file by record type and writes one parquet per
    RT under a hive-style directory:

        {output_dir}/record_type={rt}/{txt_basename}.parquet

    All columns are written as String — no semantic schema interpretation
    is applied yet. Column names are dummy placeholders:

        record_type, column_1, column_2, ..., column_N

    Streaming-friendly: uses one cheap Python pre-pass to discover the
    distinct record types and their actual field counts, then one polars
    `scan_csv → filter → sink_parquet` pass per RT so the file never has
    to fit in memory. Peak memory is bounded regardless of file size.

    Args:
        zip_path: Path to the source `.zip` containing one `.txt` file.
        output_dir: Directory under which `record_type={N}/` folders are
            created. Typically `bronze/{GSE}/{folder}/`.
        overwrite: If False, skip RTs whose output parquet already exists.

    Returns:
        Dict mapping `record_type` string → field count for that RT.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(zip_path) as zf:
        names = zf.namelist()
        txt_name = next((n for n in names if n.lower().endswith('.txt')), names[0])
        out_basename = Path(txt_name).stem

        # Extract to a temp file so polars can scan it; the zip is small and
        # the extracted .txt may be many GB — polars streams it, so this is fine.
        with tempfile.TemporaryDirectory() as td:
            zf.extract(txt_name, td)
            extracted = Path(td) / txt_name

            # Pre-pass 1 (cheap, Python): discover {rt: max n_fields seen}.
            # Just counts pipes per line; no parsing. ~1M lines/sec on a Mac.
            rt_n_fields: dict[str, int] = {}
            with open(extracted, encoding='utf-8', errors='replace') as fh:
                for line in fh:
                    if not line.strip():
                        continue
                    nf = line.count('|') + 1
                    rt = line.split('|', 1)[0]
                    if nf > rt_n_fields.get(rt, 0):
                        rt_n_fields[rt] = nf

            if not rt_n_fields:
                logger.warning(f"  No data rows found in {zip_path.name}")
                return {}

            max_cols = max(rt_n_fields.values())
            # Pre-pass 2 (streaming, polars): one filter+sink per RT.
            # `schema=` forces N columns regardless of row width; shorter
            # rows get nulls in the trailing positions. Polars streams the
            # file under the hood so memory stays bounded.
            base_schema = {f'_c{i}': pl.String for i in range(max_cols)}

            written: dict[str, int] = {}
            for rt, n_fields in sorted(
                rt_n_fields.items(),
                key=lambda kv: int(kv[0]) if kv[0].isdigit() else 999,
            ):
                rt_dir = output_dir / f"record_type={rt}"
                out_path = rt_dir / f"{out_basename}.parquet"
                if not should_process_file(out_path, overwrite):
                    logger.info(f"  RT={rt:>3}: skipping (exists) {out_path.name}")
                    written[rt] = 0
                    continue
                rt_dir.mkdir(parents=True, exist_ok=True)

                lf = pl.scan_csv(
                    extracted,
                    has_header=False,
                    separator='|',
                    schema=base_schema,
                    truncate_ragged_lines=True,
                    ignore_errors=True,
                )
                # Keep only the first `n_fields` columns for this RT; rename.
                use_cols = [f'_c{i}' for i in range(n_fields)]
                rename_map = {'_c0': 'record_type'}
                for i in range(1, n_fields):
                    rename_map[f'_c{i}'] = f'column_{i}'

                (
                    lf.filter(pl.col('_c0') == rt)
                      .select(use_cols)
                      .rename(rename_map)
                      .sink_parquet(out_path, compression='zstd')
                )
                written[rt] = n_fields
                logger.info(f"  RT={rt:>3}: {n_fields:>2} cols → {out_path.name}")

            return written


def run_multi_rt_bronze_import(
    raw_dir: Path,
    bronze_dir: Path,
    *,
    overwrite: bool = False,
    gse: str | None = None,
    folders: list[str] | None = None,
) -> dict[str, int]:
    """Import headerless multi-record-type GSE files to per-RT bronze parquets.

    Companion to `run_bronze_import` for the headerless ISS-family files
    listed in `MULTI_RECORD_TYPE_FILES`. Splits each zip into one parquet
    per record type under hive-style `record_type={N}/` partitions.

    Args:
        raw_dir: Path to the raw data root.
        bronze_dir: Path to the bronze output root.
        overwrite: If True, replace existing per-RT parquets.
        gse: Optional GSE filter ('FNMA' or 'FHLMC').
        folders: Optional list of folder names to process. Process all if None.

    Returns:
        Dict with keys 'processed', 'successful', 'failed'.

    Raises:
        FileNotFoundError: If raw_dir does not exist.
        ValueError: If `gse` is not None and not in `MULTI_RECORD_TYPE_FILES`.
    """
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw directory does not exist: {raw_dir}")

    if gse is not None and gse not in MULTI_RECORD_TYPE_FILES:
        raise ValueError(
            f"Invalid GSE: {gse!r}. Must be one of {list(MULTI_RECORD_TYPE_FILES)}"
        )

    logger.info("=" * 60)
    logger.info("GSE Multi-Record-Type Bronze Import (ISS-family)")
    logger.info("=" * 60)
    logger.info(f"Raw directory:    {raw_dir}")
    logger.info(f"Bronze directory: {bronze_dir}")
    logger.info(f"Overwrite mode:   {overwrite}")
    if gse:
        logger.info(f"GSE filter:       {gse}")
    if folders:
        logger.info(f"Folder filter:    {folders}")

    bronze_dir.mkdir(parents=True, exist_ok=True)

    # Discover zip files per GSE/folder
    folder_filter = set(folders) if folders else None
    work: dict[str, dict[str, list[Path]]] = {}
    for g, fldrs in MULTI_RECORD_TYPE_FILES.items():
        if gse and g != gse:
            continue
        g_dir = raw_dir / g
        if not g_dir.exists():
            logger.warning(f"GSE directory not found: {g}")
            continue
        for f in fldrs:
            if folder_filter and f not in folder_filter:
                continue
            fdir = g_dir / f
            if not fdir.exists():
                continue
            zips = sorted(p for p in fdir.glob('*.zip') if '_REV' not in p.name.upper())
            if zips:
                work.setdefault(g, {})[f] = zips

    total = sum(len(z) for gf in work.values() for z in gf.values())
    logger.info(f"Found {total} file(s) to process")
    logger.info("")

    processed = successful = failed = 0
    for g, gse_folders in work.items():
        logger.info(f"Processing GSE: {g}")
        logger.info("=" * 60)
        for folder, zips in gse_folders.items():
            logger.info(f"  Folder: {folder}")
            logger.info("  " + "-" * 58)
            out_root = bronze_dir / g / folder
            for zp in zips:
                processed += 1
                logger.info(f"  [{processed}/{total}] {zp.name}")
                try:
                    process_zip_to_per_rt_parquet(zp, out_root, overwrite=overwrite)
                    successful += 1
                except Exception as exc:
                    failed += 1
                    logger.error(f"  failed: {zp.name} — {exc}")
                logger.info("")

    logger.info("=" * 60)
    logger.info("MULTI-RT IMPORT SUMMARY")
    logger.info("=" * 60)
    logger.info(f"Files processed: {processed}  successful={successful}  failed={failed}")
    logger.info(f"Bronze location: {bronze_dir}")
    logger.info("=" * 60)
    return {"processed": processed, "successful": successful, "failed": failed}


