def get_zip_files(raw_dir: Path) -> dict[str, dict[str, list[Path]]]:
    """Get all zip files from the raw data directories.

    Returns a nested dictionary: {GSE: {folder: [zip_files]}}
    """
    zip_files = {}

    for gse, folders in PIPE_DELIMITED_WITH_HEADERS.items():
        gse_dir = raw_dir / gse
        zip_files[gse] = {}

        if not gse_dir.exists():
            logger.warning(f"GSE directory not found: {gse}")
            continue

        for folder in folders:
            folder_path = gse_dir / folder
            if folder_path.exists():
                zips = list(folder_path.glob('*.zip'))
                if zips:
                    zip_files[gse][folder] = zips
                    logger.info(f"Found {len(zips)} zip file(s) in {gse}/{folder}")
                else:
                    logger.warning(f"No zip files found in {gse}/{folder}")
            else:
                logger.warning(f"Folder not found: {gse}/{folder}")

    return zip_files


def process_zip_to_parquet(
    zip_path: Path,
    output_dir: Path,
    overwrite: bool = False,
    *,
    separator: str = '|',
    schema_overrides: dict[str, pl.DataType] | None = None,
) -> bool:
    """Extract a zip file, scan with polars, and sink to parquet.

    Args:
        zip_path: Path to the zip file
        output_dir: Directory where parquet file should be saved
        overwrite: If False, skip files that already exist in bronze
        separator: Field separator for the source file. Defaults to '|' for
            the standard pipe-delimited UMBS feeds; pass ',' for CSV-formatted
            feeds (e.g. FRE_Multilender).
        schema_overrides: Optional per-column dtype map. When provided, the
            CSV is parsed with these dtypes pinned instead of relying on
            polars' first-N-row inference. This is the bug-resistant path
            and the default behavior when called via `run_bronze_import`,
            which looks up the schema from `BRONZE_SCHEMAS`.

    Returns:
        True if successful, False otherwise
    """
    try:
        # Create output directory if it doesn't exist
        output_dir.mkdir(parents=True, exist_ok=True)

        # Get the zip file info
        with zipfile.ZipFile(zip_path, 'r') as zip_ref:
            file_list = zip_ref.namelist()

            if len(file_list) != 1:
                logger.warning(f"{zip_path.name} contains {len(file_list)} files, expected 1")
                txt_files = [f for f in file_list if f.endswith('.txt')]
                if not txt_files:
                    logger.error(f"No .txt file found in {zip_path.name}")
                    return False
                txt_file = txt_files[0]
            else:
                txt_file = file_list[0]

            # Check uncompressed size
            file_info = zip_ref.getinfo(txt_file)
            size_mb = file_info.file_size / (1024 * 1024)
            logger.info(f"Processing {zip_path.name} -> {txt_file} ({size_mb:.2f} MB uncompressed)")

            if size_mb > 500:
                logger.warning(f"Large file detected: {size_mb:.2f} MB")

            # Extract to temporary directory and process
            with tempfile.TemporaryDirectory() as temp_dir:
                temp_path = Path(temp_dir)
                zip_ref.extract(txt_file, temp_path)
                extracted_file = temp_path / txt_file

                # Create output filename (same as txt file but with .parquet extension)
                output_file = output_dir / Path(txt_file).with_suffix('.parquet').name

                # Check if file exists and skip if overwrite is False
                if not should_process_file(output_file, overwrite):
                    logger.info(f"Skipping {output_file.name} (already exists, use --overwrite to rebuild)")
                    return True

                # Use polars to scan and convert to parquet
                logger.info(f"Scanning {txt_file} with polars...")

                # Scan with the appropriate delimiter. When schema_overrides
                # is supplied, polars uses those dtypes instead of inferring
                # from the first ~100 rows — this prevents the silent-null
                # bug where heterogeneous-prefix files (e.g. FNM_MLLD) had
                # `Security Identifier` inferred as Int64 from numeric-ID
                # rows and then alphanumeric IDs got nulled by `ignore_errors`.
                scan_kwargs = dict(
                    separator=separator,
                    encoding='utf8',
                    has_header=True,
                    ignore_errors=True,
                    truncate_ragged_lines=True,
                )
                if schema_overrides:
                    scan_kwargs['schema_overrides'] = schema_overrides
                df = pl.scan_csv(extracted_file, **scan_kwargs)

                # Sink to parquet
                logger.info(f"Writing to {output_file.relative_to(output_file.parents[2])}")
                df.sink_parquet(output_file, compression='zstd')

                logger.info(f"Successfully processed {zip_path.name}")
                return True

    except Exception as e:
        logger.error(f"Error processing {zip_path.name}: {str(e)}")
        return False


def run_bronze_import(
    raw_dir: Path,
    bronze_dir: Path,
    *,
    overwrite: bool = False,
    gse: str | None = None,
    folders: list[str] | None = None,
) -> dict[str, int]:
    """Import GSE raw zip files to bronze parquet.

    Args:
        raw_dir: Path to the raw data directory.
        bronze_dir: Path to the bronze output directory.
        overwrite: If True, replace existing parquet files.
        gse: Optional GSE filter ('FNMA' or 'FHLMC'). Process both if None.
        folders: Optional list of folder names to process. Process all if None.

    Returns:
        Dict with keys 'processed', 'successful', 'failed'.

    Raises:
        FileNotFoundError: If raw_dir does not exist.
        ValueError: If gse is not None and not 'FNMA' or 'FHLMC'.
    """
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw directory does not exist: {raw_dir}")

    if gse is not None and gse not in PIPE_DELIMITED_WITH_HEADERS:
        raise ValueError(f"Invalid GSE: {gse!r}. Must be one of {list(PIPE_DELIMITED_WITH_HEADERS)}")

    logger.info("=" * 60)
    logger.info("GSE Data Import: Raw to Bronze (FNMA & FHLMC)")
    logger.info("=" * 60)
    logger.info(f"Raw directory: {raw_dir}")
    logger.info(f"Bronze directory: {bronze_dir}")
    logger.info(f"Overwrite mode: {overwrite}")
    if gse:
        logger.info(f"GSE filter: {gse}")
    if folders:
        logger.info(f"Folder filter: {folders}")
    logger.info("")

    # Create bronze directory
    bronze_dir.mkdir(parents=True, exist_ok=True)

    # Get all zip files
    zip_files = get_zip_files(raw_dir)

    # Apply GSE filter
    if gse is not None:
        zip_files = {k: v for k, v in zip_files.items() if k == gse}

    # Apply folder filter
    if folders is not None:
        folder_set = set(folders)
        zip_files = {
            g: {f: zips for f, zips in gse_folders.items() if f in folder_set}
            for g, gse_folders in zip_files.items()
        }

    if not any(gse_folders for gse_folders in zip_files.values()):
        logger.warning("No zip files found to process")
        return {"processed": 0, "successful": 0, "failed": 0}

    # Process each GSE's folders and zip files
    total_files = sum(
        len(files)
        for gse_folders in zip_files.values()
        for files in gse_folders.values()
    )
    processed = 0
    successful = 0
    failed = 0

    logger.info(f"Found {total_files} total file(s) to process")
    logger.info("")

    for gse_name, gse_folders in zip_files.items():
        if not gse_folders:
            continue

        logger.info(f"Processing GSE: {gse_name}")
        logger.info("=" * 60)

        for folder, zip_list in gse_folders.items():
            logger.info(f"  Folder: {folder}")
            logger.info("  " + "-" * 58)

            # Create corresponding bronze subfolder (preserves GSE structure)
            bronze_subfolder = bronze_dir / gse_name / folder
            sep = _separator_for(gse_name, folder)
            # Look up the pinned column schema for this (GSE, folder). If
            # the folder isn't in BRONZE_SCHEMAS yet (e.g. brand-new feed),
            # we fall back to polars inference with a warning so the import
            # still works but the user knows to regenerate schemas.py.
            schema = BRONZE_SCHEMAS.get(gse_name, {}).get(folder)
            if schema is None:
                logger.warning(
                    f"  {gse_name}/{folder}: no schema in BRONZE_SCHEMAS — "
                    f"falling back to polars inference. Re-run "
                    f"`python -m mortgage_data_manager.umbs.schemas build` "
                    f"to add this folder."
                )

            for zip_path in zip_list:
                processed += 1
                logger.info(f"  [{processed}/{total_files}] {zip_path.name}")

                if process_zip_to_parquet(
                    zip_path, bronze_subfolder, overwrite,
                    separator=sep, schema_overrides=schema,
                ):
                    successful += 1
                else:
                    failed += 1

                logger.info("")

        logger.info("")

    # Summary
    logger.info("=" * 60)
    logger.info("IMPORT SUMMARY")
    logger.info("=" * 60)
    logger.info(f"Total files processed: {processed}")
    logger.info(f"Successful: {successful}")
    logger.info(f"Failed: {failed}")
    if processed > 0:
        logger.info(f"Success rate: {(successful / processed * 100):.1f}%")
    logger.info("")
    logger.info(f"Bronze data location: {bronze_dir}")
    logger.info("=" * 60)

    return {"processed": processed, "successful": successful, "failed": failed}


