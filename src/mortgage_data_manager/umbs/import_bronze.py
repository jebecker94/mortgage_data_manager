"""Import GSE (FNMA and FHLMC) raw data files to bronze layer in parquet format.

This script processes pipe-delimited files with headers from the data/raw
directory and converts them to parquet format in data/bronze, preserving
the GSE and folder structure.

Two import paths live in this module:

1. `run_bronze_import` (and its `PIPE_DELIMITED_WITH_HEADERS` dict)
   — for genuinely pipe-delimited files with header rows. One parquet
   per source zip, schema = the header row.

2. `run_multi_rt_bronze_import` (and its `MULTI_RECORD_TYPE_FILES` dict)
   — for the headerless ISS-family files (`FNM_ISS`, `FNM_RISS`, `FRE_ISS`,
   `FRE_RISS`, `FNM_MS`, `FQ`, `GE`, `MJ`, `XS`, `MZ`). These multiplex
   multiple record types into one file with field 0 as the record-type
   code; field count depends on the record type. Output is hive-partitioned
   per record type: `bronze/{GSE}/{folder}/record_type={rt}/<file>.parquet`.
   See investigations/reports/investigation_iss_schema_recovery_2026-05-24.md.

Excludes from BOTH paths (require bespoke handling):
FNMA:
- SIFMA (fixed-width format)
- REMICSUP (fixed-width format)
- FNM_DEALERREPORT (Excel format)
- RC (fixed-width, 617-char records, no .txt extension)
- FNM_MICA (quarterly reference: two CSVs per zip, uppercase .ZIP)
- NODELAY (formatted plaintext report)
- WLPSEUDO (formatted plaintext report)

FHLMC:
- WR (printable report with page headers, space-aligned columns)
- CFILE (PDF documents)
- FRE_MICA (quarterly reference: two CSVs per zip)
"""

